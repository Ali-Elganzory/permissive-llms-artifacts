def heldout_reasoning(out: Path) -> Path:
    order = ["MixtureVitae", "Comma0.1", "FineWeb-Edu", "Nemotron-CC-HQ", "SmolLM2"]
    lines = [
        r"\begin{table}[t]", r"\centering",
        r"\caption{\textbf{The reasoning gain is not tied to OpenThoughts3.} Change in "
        r"MATH500 accuracy when each base's Tulu3 SFT checkpoint receives 30K samples from "
        r"one of four reasoning corpora, three of which are absent from every pre-training "
        r"mixture considered here. Brackets are 95\% paired bootstrap intervals over the same "
        r"500 problems. \textbf{Bold} marks a significant increase and \emph{italic} a "
        r"significant decrease after Benjamini--Hochberg correction. " + PROTOCOL_B_NOTE + r"}",
        r"\label{tab:heldout_reasoning}", r"\small", r"\setlength{\tabcolsep}{4pt}",
        r"\resizebox{\linewidth}{!}{%",
        r"\begin{tabular}{l" + "r" * len(pb.HELDOUT_CORPORA) + "}", r"\toprule",
        r"\textbf{Base} & " + " & ".join(f"\\textbf{{{c}}}" for c in pb.HELDOUT_CORPORA)
        + r" \\", r"\midrule",
    ]
    for base in order:
        cells = []
        for est, lo, hi, sig in pb.HELDOUT_MATH500[base]:
            txt = f"${est:+.1f}$ {{\\scriptsize$[{lo:+.1f}, {hi:+.1f}]$}}"
            if sig == "+":
                txt = f"$\\bm{{{est:+.1f}}}$ {{\\scriptsize$[{lo:+.1f}, {hi:+.1f}]$}}"
            elif sig == "-":
                txt = f"\\emph{{${est:+.1f}$}} {{\\scriptsize$[{lo:+.1f}, {hi:+.1f}]$}}"
            cells.append(txt)
        name = base
        lines.append(name + " & " + " & ".join(cells) + r" \\")
        if base == "MixtureVitae":
            lines.append(r"\midrule")
    lines += [r"\bottomrule", r"\end{tabular}}", r"\end{table}", ""]
    return _write(out, "heldout_reasoning.tex", "\n".join(lines))


def heldout_mv_grid(out: Path) -> Path:
    lines = [
        r"\begin{table}[t]", r"\centering",
        r"\caption{Full held-out reasoning grid for MixtureVitae: four reasoning corpora "
        r"applied from three starting checkpoints, with recipe, sample budget, and epoch "
        r"count held fixed so that only the identity of the reasoning corpus changes. "
        r"``--'' marks a benchmark that was not evaluated, and that row's average is taken "
        r"over the remaining ten. " + PROTOCOL_B_NOTE + r"}",
        r"\label{tab:heldout_mv_grid}", r"\scriptsize", r"\setlength{\tabcolsep}{3pt}",
        r"\resizebox{\linewidth}{!}{%",
        r"\begin{tabular}{l" + "r" * 12 + "}", r"\toprule",
        r"\textbf{Reasoning corpus} & " + " & ".join(f"\\textbf{{{b}}}" for b in pb.BENCH_ORDER)
        + r" & \textbf{Avg} \\",
    ]
    for stage in ("base", "sft", "dpo"):
        lines.append(r"\midrule")
        lines.append(r"\multicolumn{13}{l}{\emph{Starting from the "
                     + pb.STARTING_POINT_LABEL[stage] + r" checkpoint}} \\")
        start_avg = pb.HELDOUT_MV_GRID[stage][0][1][11]
        for label, vals in pb.HELDOUT_MV_GRID[stage]:
            cells = " & ".join("--" if v is None else f"{v:.1f}" for v in vals)
            if label == "starting checkpoint":
                lines.append(r"\quad \emph{starting checkpoint} & " + cells + r" \\")
            else:
                delta = vals[11] - start_avg
                lines.append(f"\\quad {label} & " + cells
                             + r"~" + f"{{\\scriptsize(${delta:+.1f}$)}}" + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}}", r"\end{table}", ""]
    return _write(out, "heldout_mv_grid.tex", "\n".join(lines))
