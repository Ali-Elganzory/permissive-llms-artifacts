def phase2_endpoints(out: Path) -> Path:
    lines = [
        r"\begin{table}[t]", r"\centering",
        r"\caption{Reasoning post-training endpoints. Identical OpenThoughts3-30K "
        r"post-training (30K samples, 5 epochs) is applied to every model, starting from the "
        r"checkpoint named in each block's first row. Starting checkpoints are re-evaluated "
        r"here, so these values are paired within the table and must not be compared against "
        r"the Phase~1 tables. " + PROTOCOL_B_NOTE + r"}",
        r"\label{tab:phase2_endpoints}", r"\scriptsize", r"\setlength{\tabcolsep}{3pt}",
        r"\resizebox{\linewidth}{!}{%",
        r"\begin{tabular}{l" + "r" * 12 + "}", r"\toprule",
        r"\textbf{Model} & " + " & ".join(f"\\textbf{{{b}}}" for b in pb.BENCH_ORDER)
        + r" & \textbf{Avg} \\", r"\midrule",
    ]
    current = None
    for group, row_label, is_start, vals in pb.PHASE2_ENDPOINTS:
        if group != current:
            if current is not None:
                lines.append(r"\midrule")
            current = group
            name = f"{group} {row_label}" if row_label != "base" else f"{group} (base)"
        else:
            name = r"\quad " + row_label.replace(r"\quad ", "")
        lines.append(name + " & " + " & ".join(f"{v:.1f}" for v in vals) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}}", r"\end{table}", ""]
    return _write(out, "phase2_endpoints.tex", "\n".join(lines))


