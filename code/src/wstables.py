"""Generate LaTeX tables from CSV-derived summaries and supplied Protocol B results."""

from __future__ import annotations

from pathlib import Path

import numpy as np
import pandas as pd

import protocol_b as pb
from wsdata import (BENCH_ABBR, BENCHMARKS, DOMAINS, LANGUAGE_ABBR, LANGUAGE_TASKS,
                    POOL_LABEL, POOLS, STAGES, ZOO_LABEL, ZOO_ORDER, ZOO_TOKENS)

HEADER = ("% Generated by generate_workshop_artifacts.py. Do not edit by hand.\n")

PROTOCOL_A_NOTE = (
    "Protocol~A (Appendix Table~\\ref{tab:eval-settings-A}). "
    "Values are mean$_{\\pm\\text{SD}}$ over decoding seeds 42, 1234, and 2025."
)
PROTOCOL_B_NOTE = (
    "Protocol~B, the reasoning post-training protocol (Appendix Table~\\ref{tab:eval-settings-B}). "
    "Single seed, so no error bars are available."
)
STAGE_HEAD = {"base": "Base", "sft": "SFT", "dpo": "DPO"}


def _write(out: Path, name: str, body: str) -> Path:
    path = out / name
    path.write_text(HEADER + body)
    return path


def _ms(mean: float, sd: float) -> str:
    return f"{mean:.1f}$_{{\\pm{sd:.2f}}}$"


def _score_lookup(scores: pd.DataFrame, keys: dict, benchmark: str) -> tuple[float, float]:
    sel = scores
    for k, v in keys.items():
        sel = sel[sel[k] == v]
    row = sel[sel["benchmark"] == benchmark]
    return round(float(row["mean"].iloc[0]), 1), round(float(row["sd"].iloc[0]), 2)


